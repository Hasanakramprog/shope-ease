class ShippingAddress {
  String fullName;
  String addressLine1;
  String addressLine2;
  String city;
  String state;
  String zipCode;
  String country;
  String phoneNumber;

  ShippingAddress({
    required this.fullName,
    required this.addressLine1,
    required this.addressLine2,
    required this.city,
    required this.state,
    required this.zipCode,
    required this.country,
    required this.phoneNumber,
  });
}